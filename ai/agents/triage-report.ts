import type { UsageSummary } from "../core/cost-log";
import type { TriageReport } from "./triage-schema";

// Human outputs of the triage: reports/ai-triage.md and an optional Teams message.

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const mins = (ms: number) =>
  ms >= 60_000 ? `${(ms / 60_000).toFixed(1)} min` : `${(ms / 1000).toFixed(0)} s`;
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const ICON: Record<string, string> = {
  PRODUCT_BUG: "🐞",
  ENVIRONMENT: "🌩️",
  TEST_ISSUE: "🧪",
  FLAKY: "🎲",
  UNKNOWN: "❓",
};

export function renderMarkdown(r: TriageReport, usage?: UsageSummary): string {
  const out: string[] = [];
  out.push(
    `# Failure triage — ${r.run.releaseVersion ? `release ${r.run.releaseVersion}, ` : ""}run ${r.run.runId}`,
  );
  out.push("");
  out.push(
    `**${r.stats.total}** tests · ✅ ${r.stats.passed} passed · ❌ ${r.stats.failed} failed · 🎲 ${r.stats.flaky} flaky · ⏭️ ${r.stats.skipped} skipped · pass rate **${pct(r.stats.passRate)}** · ${mins(r.stats.durationMs)}`,
  );
  if (r.run.buildUrl) out.push(`\nBuild: ${r.run.buildUrl}`);
  out.push(
    `\nClassifier: rules${r.llm.provider !== "none" ? ` + LLM (${r.llm.provider} / ${r.llm.model}, ${r.llm.calls} calls)` : " only (LLM_PROVIDER=none)"}`,
  );

  out.push("\n## Totals by category\n");
  out.push("| Category | Failures |", "|---|---|");
  for (const [cat, n] of Object.entries(r.totals)) out.push(`| ${ICON[cat]} ${cat} | ${n} |`);

  if (r.globalErrors.length) {
    out.push("\n## Errors outside tests\n");
    for (const e of r.globalErrors) out.push(`- ${esc(e.split("\n")[0])}`);
  }

  out.push("\n## Top clusters (one row per root cause)\n");
  if (r.clusters.length === 0) out.push("No failures 🎉");
  else {
    out.push(
      "| # | Category | Tests | New? | Error | Reason | Bug |",
      "|---|---|---|---|---|---|---|",
    );
    r.clusters.slice(0, 15).forEach((c, i) => {
      out.push(
        `| ${i + 1} | ${ICON[c.category]} ${c.category} (${c.kind}, ${c.confidence}) | ${c.count} | ${c.isNew ? "🆕" : "known"} | \`${esc(c.sampleError).slice(0, 120)}\` | ${esc(c.reason).slice(0, 200)} | ${c.bugId ? `[#${c.bugId}](${c.bugUrl ?? ""})` : ""} |`,
      );
    });
    if (r.clusters.length > 15)
      out.push(`\n…and ${r.clusters.length - 15} more clusters in ai-triage.json`);
  }

  const newFailures = r.items.filter((i) => i.isNew && i.category !== "FLAKY");
  out.push(`\n## New failures (${newFailures.length})\n`);
  for (const i of newFailures.slice(0, 30))
    out.push(`- ${ICON[i.category]} **${esc(i.title)}** (${i.project}) — ${esc(i.errorSummary)}`);

  const known = r.items.filter((i) => !i.isNew && i.category !== "FLAKY");
  if (known.length) {
    out.push(`\n## Still failing from previous runs (${known.length})\n`);
    for (const i of known.slice(0, 30))
      out.push(
        `- **${esc(i.title)}** — failing since ${i.history.failingSince ?? "?"} (${i.history.consecutiveFailures + 1} runs)`,
      );
  }

  const flaky = r.items.filter((i) => i.category === "FLAKY");
  out.push(`\n## Flaky (${flaky.length})\n`);
  for (const i of flaky) out.push(`- **${esc(i.title)}** (${i.project}) — ${esc(i.reason)}`);

  const withTraces = r.items.filter((i) => i.attachments.some((a) => a.name === "trace"));
  if (withTraces.length) {
    out.push("\n## Traces\n");
    out.push(
      "Open with `npx playwright show-trace <path>` (paths are inside the html-report / test-results artifacts).\n",
    );
    for (const i of withTraces.slice(0, 20))
      out.push(`- ${esc(i.title)}: \`${i.attachments.find((a) => a.name === "trace")?.path}\``);
  }

  if (usage && usage.calls > 0) {
    out.push("\n## AI cost\n");
    out.push(
      `${usage.calls} LLM calls · ${usage.inputTokens} input / ${usage.outputTokens} output tokens · ~$${usage.costUsd.toFixed(4)}`,
    );
    for (const [agent, a] of Object.entries(usage.byAgent))
      out.push(`- ${agent}: ${a.calls} calls, ~$${a.costUsd.toFixed(4)}`);
  }

  out.push(
    "\n---\n_Generated by ai/agents/triage.agent.ts. Categories are suggestions: a human confirms before acting._",
  );
  return out.join("\n") + "\n";
}

/** Adaptive Card payload for a Teams "Workflows" incoming webhook. */
export function teamsMessage(r: TriageReport): unknown {
  const facts = Object.entries(r.totals)
    .filter(([, n]) => n > 0)
    .map(([cat, n]) => ({ title: `${ICON[cat]} ${cat}`, value: String(n) }));
  return {
    type: "message",
    attachments: [
      {
        contentType: "application/vnd.microsoft.card.adaptive",
        content: {
          $schema: "http://adaptivecards.io/schemas/adaptive-card.json",
          type: "AdaptiveCard",
          version: "1.4",
          body: [
            {
              type: "TextBlock",
              size: "Large",
              weight: "Bolder",
              text: `Regression ${r.run.releaseVersion ?? r.run.runId}: ${pct(r.stats.passRate)} pass rate`,
            },
            {
              type: "TextBlock",
              wrap: true,
              text: `${r.stats.failed} failed · ${r.stats.flaky} flaky · ${r.stats.total} tests`,
            },
            { type: "FactSet", facts },
            ...r.clusters.slice(0, 5).map((c) => ({
              type: "TextBlock",
              wrap: true,
              text: `${ICON[c.category]} ${c.count}× ${c.sampleError.slice(0, 140)}`,
            })),
          ],
          actions: r.run.buildUrl
            ? [{ type: "Action.OpenUrl", title: "Open build", url: r.run.buildUrl }]
            : [],
        },
      },
    ],
  };
}
