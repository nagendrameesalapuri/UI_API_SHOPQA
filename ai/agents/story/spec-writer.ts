import type { Scenario } from "./acceptance-parser";
import { type PageMethod, suggestMethods } from "./page-index";

// Template-based outputs of the Story-to-Test agent (no LLM needed):
//  - specs/story-<id>.md: the scenario plan a human reviews
//  - tests/ui/stories/story-<id>.spec.ts: compilable skeleton with test.step per
//    Given/When/Then; every test is test.fixme until a human (or the LLM) fills it in.

export type StoryInfo = {
  id: number;
  title: string;
  description: string;
  acceptanceCriteria: string;
  linkedTestCases: number[];
  url?: string;
};

const q = (s: string) => JSON.stringify(s);

/** Given/When/Then with "And" for the 2nd+ step of a section, as in Gherkin. */
export function labelledSteps(s: Scenario): [string, string][] {
  const section = (kw: string, steps: string[]) =>
    steps.map((t, i): [string, string] => [i === 0 ? kw : "And", t]);
  return [...section("Given", s.given), ...section("When", s.when), ...section("Then", s.then)];
}
const comment = (s: string) => s.replace(/\*\//g, "* /").replace(/\n/g, " ");

export function renderPlanMarkdown(
  story: StoryInfo,
  scenarios: Scenario[],
  meta: { source: "rules" | "llm" },
): string {
  const out: string[] = [];
  out.push(`# Test plan: story ${story.id} — ${story.title}`, "");
  out.push(`- Source: ${story.url ?? `work item ${story.id}`}`);
  out.push(
    `- Generated by: story-to-test agent (${meta.source === "llm" ? "LLM-assisted" : "rule-based, LLM_PROVIDER=none"})`,
  );
  out.push(
    `- Linked Test Cases: ${story.linkedTestCases.length ? story.linkedTestCases.join(", ") : "none"}`,
  );
  out.push("- Status: **DRAFT — needs human review** (look for TODO)", "");
  out.push(`Seed: \`tests/seed.spec.ts\``, "");
  scenarios.forEach((s, i) => {
    out.push(`## ${i + 1}. ${s.title}${s.tcId ? ` (TC ${s.tcId})` : ""}`, "");
    out.push(`Type: ${s.type} · Level: ${s.level} · Tags: ${s.tags.join(" ")}`, "");
    for (const [kw, text] of labelledSteps(s)) out.push(`- **${kw}** ${text}`);
    if (s.assumptions.length) {
      out.push("", "Assumptions / open questions:");
      for (const a of s.assumptions) out.push(`- ${a}`);
    }
    out.push("");
  });
  return out.join("\n");
}

export function renderSpecSkeleton(
  story: StoryInfo,
  scenarios: Scenario[],
  index: PageMethod[],
): string {
  const lines: string[] = [];
  lines.push(`import { test } from "../../../src/fixtures";`, "");
  lines.push(
    `// Generated by the story-to-test agent from work item ${story.id}. DRAFT for review.`,
  );
  lines.push("// Every test is test.fixme until its steps use real page-object calls.");
  lines.push(
    "// Rules: page objects only (no raw locators), no waitForTimeout, one behaviour per test.",
    "",
  );
  lines.push(`test.describe(${q(`@Story-${story.id} ${story.title}`)}, () => {`);
  scenarios.forEach((s, i) => {
    const tags = [...s.tags, ...(s.tcId ? [`@TC-${s.tcId}`] : [])].join(" ");
    if (i > 0) lines.push("");
    lines.push(`  // TODO: implement with page objects, then change test.fixme to test`);
    lines.push(`  test.fixme(${q(`${tags} ${s.title}`)}, async () => {`);
    for (const [n, [kw, text]] of labelledSteps(s).entries()) {
      if (n > 0) lines.push("");
      lines.push(`    await test.step(${q(`${kw} ${text}`)}, async () => {`);
      const hints = suggestMethods(text, index);
      if (hints.length)
        lines.push(
          `      // Candidate page-object calls: ${hints.map((h) => `${h.fixture}.${h.signature}`).join(" | ")}`,
        );
      else
        lines.push(
          `      // TODO: no matching page-object method found: add one to pages/ (${comment(text).slice(0, 80)})`,
        );
      lines.push("    });");
    }
    lines.push("  });");
  });
  lines.push("});", "");
  return lines.join("\n");
}
